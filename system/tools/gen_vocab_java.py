"""Generate the Java vocabulary for the Android engine from the Python one (lpr/vocab.py + models/vocab.json),
so both use exactly the same 101 tokens, token kinds, spelling variants and English names.

  python tools/gen_vocab_java.py   ->  android/app/src/main/java/bd/nsu/banglalpr/core/VocabData.java
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
sys.path.insert(0, ROOT)
from lpr import vocab  # noqa: E402

classes = json.load(open(os.path.join(ROOT, 'models', 'vocab.json'), encoding='utf-8'))['classes']
p10 = json.load(open(os.path.join(ROOT, 'models', 'weights', 'p10_class_names.json'), encoding='utf-8'))


def jstr(s):
    return '"' + ''.join(c if 32 <= ord(c) < 127 and c not in '"\\' else f'\\u{ord(c):04x}' for c in s) + '"'


def arr(xs):
    return '{' + ', '.join(jstr(x) for x in xs) + '}'


kinds = {k: v for k, v in vocab.KIND.items()}
eng = {k: v for k, v in vocab.ENGLISH.items()}
out = f"""package bd.nsu.banglalpr.core;

// GENERATED by tools/gen_vocab_java.py from lpr/vocab.py and models/vocab.json. Do not edit by hand.
final class VocabData {{
    private VocabData() {{}}
    /** the 101 reader classes (index + 1 = model class id for CTC / slot readers; index = class id for char-YOLO) */
    static final String[] CLASSES = {arr(classes)};
    /** class order of the BLPnet character CNN (paper10.ipynb class_names.json) */
    static final String[] P10_CLASSES = {arr(p10)};
    static final String[] KIND_KEYS = {arr(list(kinds))};
    static final String[] KIND_VALUES = {arr(list(kinds.values()))};
    static final String[] VARIANT_KEYS = {arr(list(vocab.VARIANTS))};
    static final String[] VARIANT_VALUES = {arr(list(vocab.VARIANTS.values()))};
    static final String[] ENGLISH_KEYS = {arr(list(eng))};
    static final String[] ENGLISH_VALUES = {arr(list(eng.values()))};
    static final String METRO = {jstr(vocab.METRO)};
    static final String DIGITS = {jstr(''.join(vocab.DIGITS))};
}}
"""
dst = os.path.join(ROOT, 'android', 'app', 'src', 'main', 'java', 'bd', 'nsu', 'banglalpr', 'core', 'VocabData.java')
os.makedirs(os.path.dirname(dst), exist_ok=True)
open(dst, 'w', encoding='ascii').write(out)
print('wrote', dst, len(classes), 'classes')
